"""P131 (2026-11-12, audit «глибина в кожному елементі»): a synth whose every note is ALIVE. Until now a tonal layer was one recording
resampled to each pitch (sfz.oneshot): every note the same waveform, only louder or quieter; «movement» was a crossfade between
low-passed copies of the whole layer. A produced electronic sound moves inside each note and from note to note: the filter opens
with the envelope and with velocity, an LFO runs across the phrase, voices drift, and one part reacts to another.

    from autodj.compose.synth import Synth, patch
    p = patch(osc=[dict(wave="saw", unison=5, detune=14, spread=.6), dict(wave="sine", semi=-12, level=.5)],
              filt=dict(cutoff=180, res=.35, env=3.5, vel=1.5, key=.3, drive=6), amp=dict(a=.002, d=.2, s=.3, r=.08),
              fenv=dict(a=.001, d=.14, s=0, r=.1),
              mods=[dict(src="lfo", dst="cutoff", amt=.8, rate="2b"),            # a slow sweep across two bars (same for all notes)
                    dict(src="rand", dst="cutoff", amt=.2),                      # no two notes identical
                    dict(src="ctl:hats", dst="cutoff", amt=-1.0),                # closes while the hats play: parts that listen
                    dict(src="time", dst="res", amt=.3)])                        # the sound itself develops over the track
    x = Synth(p, bpm=trk.bpm, seed=seed).render(events, total_s, ctl={"hats": trk.follow("hats")})    # events (t, midi, vel, dur)

Oscillators: saw / pulse (band-limited, polyBLEP), tri, sine, noise, fm (2-operator phase modulation), wt (wavetable with
position morph: tables from ANY recording via wavetable_from_audio, or generated by procedural_table).
Filter: zero-delay state-variable lp / bp / hp, 12 or 24 dB, cutoff modulated per sample-block inside every note (filt.per="note")
or one shared filter for the whole layer (per="layer", string-machine style, fast for long pad notes; "auto" picks by note length;
there the cutoff / res follow the note envelopes plus the lfo, time and ctl sources, all other routings work per note as usual).
Mod sources: env, amp_env, vel, rand, lfo (tempo-synced, global), lfo_note (restarts per note), pos (place in the bar), time (place
in the track), ctl:NAME (any curve, e.g. Track.follow of another layer or an energy curve).
Destinations: cutoff (octaves), pitch (semitones), amp (dB), res, pan, pw, index, pos, detune (x).
Pure numpy/scipy (the filter loop is compiled by numba when it is installed); deterministic by seed."""
import copy, os
import numpy as np
from scipy.signal import resample_poly, lfilter

SR = 44100
CTL = 32                         # the filter cutoff is updated every CTL samples
CAP = 6_000_000                  # max samples x notes of one batch (memory)
TABLE = 2048
DEFAULT = {"osc": [{"wave": "saw", "level": 1.0, "semi": 0.0, "cents": 0.0, "unison": 1, "detune": 0.0, "spread": 0.0, "pw": .5,
                    "ratio": 2.0, "index": 0.0, "pos": 0.0, "table": None, "phase": None}],
           "filt": {"mode": "lp", "poles": 4, "cutoff": 1200.0, "res": .15, "env": 0.0, "key": 0.0, "vel": 0.0, "drive": 0.0, "per": "auto"},
           "amp": {"a": .003, "d": .25, "s": .7, "r": .12, "vel": .6}, "fenv": {"a": .002, "d": .18, "s": 0.0, "r": .12},
           "glide_ms": 0.0, "drift": 3.0, "mods": [], "os": 0, "fx": {}}
DESTS = ("cutoff", "pitch", "amp", "res", "pan", "pw", "index", "pos", "detune")

def patch(base=None, **kw):
    """a full patch dict: DEFAULT <- base <- kw (sections are merged key by key; every osc entry is completed from the default osc)"""
    p = copy.deepcopy(DEFAULT)
    for src in (base or {}, kw):
        for k, v in src.items():
            if isinstance(v, dict) and isinstance(p.get(k), dict): p[k] = {**p[k], **copy.deepcopy(v)}
            else: p[k] = copy.deepcopy(v)
    p["osc"] = [{**DEFAULT["osc"][0], **o} for o in p["osc"]]
    for m in p["mods"]:
        if m.get("dst") not in DESTS: raise ValueError(f"mod destination {m.get('dst')!r} not in {DESTS}")
    return p

def rate_hz(rate, bpm):
    """LFO rate: a number (Hz), a note value "1/8", "1/4.", "1/8t" (one cycle per that note) or bars "2b" (one cycle per 2 bars)"""
    if isinstance(rate, (int, float)): return float(rate)
    r = str(rate).strip(); bar = 240.0 / bpm
    if r.endswith("b"): return 1.0 / (float(r[:-1]) * bar)
    mul = 1.5 if r.endswith(".") else 2 / 3 if r.endswith("t") else 1.0; a, b = r.rstrip(".t").split("/")
    return 1.0 / (bar * float(a) / float(b) * mul)

# ---- oscillators ------------------------------------------------------------------------------------------------------
def _saw(ph, dt):
    p = ph % 1.0; y = 2.0 * p - 1.0; t1 = p / dt; t2 = (p - 1.0) / dt
    return y - np.where(p < dt, 2 * t1 - t1 * t1 - 1.0, np.where(p > 1.0 - dt, t2 * t2 + 2 * t2 + 1.0, 0.0))

def mipmap(table):
    """(K, TABLE) single cycles -> (levels, K, TABLE): level j keeps only the first TABLE / 2^(j+1) harmonics (no aliasing when a note
    picks the level whose harmonics stay under Nyquist)"""
    T = np.atleast_2d(np.asarray(table, np.float64)); F = np.fft.rfft(T, axis=1); out = []
    h = T.shape[1] // 2
    while h >= 1:
        G = F.copy(); G[:, h + 1:] = 0; G[:, 0] = 0; out.append(np.fft.irfft(G, T.shape[1], axis=1)); h //= 2
    M = np.array(out); return (M / (np.abs(M[0]).max() + 1e-12)).astype(np.float32)

def _wt(mip, ph, pos, fmax, sr):
    """bilinear lookup: phase along the cycle, pos (0..1) across the frames; one mip level per note from its highest frequency"""
    Lv, K, T = mip.shape
    need = np.maximum(1.0, sr / 2.0 / np.maximum(fmax, 1.0))                                   # harmonics that fit, per note
    lvl = np.clip(np.ceil(np.log2((T // 2) / need)).astype(int), 0, Lv - 1)[None, :]
    x = (ph % 1.0) * T; i0 = x.astype(np.int64) % T; fr = (x - np.floor(x)).astype(np.float32); i1 = (i0 + 1) % T
    kf = np.clip(pos, 0, 1) * (K - 1); k0 = np.floor(kf).astype(np.int64); k1 = np.minimum(k0 + 1, K - 1); kw = (kf - k0).astype(np.float32)
    a = mip[lvl, k0, i0] * (1 - fr) + mip[lvl, k0, i1] * fr; b = mip[lvl, k1, i0] * (1 - fr) + mip[lvl, k1, i1] * fr
    return a * (1 - kw) + b * kw

def wavetable_from_audio(x, sr=SR, frames=8, f0=None, harmonics=256):
    """turn ANY recording (a Rhodes note, a conga, a spoken vowel, a field recording) into a wavetable: `frames` moments across the
    sound, each resynthesised as one cycle from the spectrum sampled at the harmonics of f0 (estimated if None; for noisy sources
    the harmonics simply trace the spectral envelope, so the synth «speaks» with that sound's colour). Returns (frames, TABLE)."""
    m = np.asarray(x, np.float64); m = m.mean(1) if m.ndim == 2 else m
    idx = np.where(np.abs(m) > np.abs(m).max() * .02)[0]
    if not len(idx): raise ValueError("silent source")
    m = m[idx[0]:idx[-1] + 1]; W = 4096
    if len(m) < W: m = np.pad(m, (0, W - len(m)))
    if f0 is None:
        seg = m[len(m) // 4:len(m) // 4 + W] * np.hanning(W); ac = np.correlate(seg, seg, "full")[W - 1:]
        lo, hi = int(sr / 1000), int(sr / 50); k = lo + int(np.argmax(ac[lo:hi])); f0 = sr / k if ac[k] > .3 * ac[0] else 110.0
    out = []
    for c in np.linspace(0, len(m) - W, frames).astype(int):
        S = np.fft.rfft(m[c:c + W] * np.hanning(W)); fr = np.fft.rfftfreq(W, 1 / sr); h = np.arange(1, harmonics + 1) * f0; ok = h < sr / 2 - 100
        amp = np.interp(h[ok], fr, np.abs(S)); ph = np.interp(h[ok], fr, np.unwrap(np.angle(S)))
        spec = np.zeros(TABLE // 2 + 1, complex); spec[1:1 + ok.sum()] = amp * np.exp(1j * ph); cyc = np.fft.irfft(spec, TABLE)
        out.append(cyc / (np.sqrt(np.mean(cyc ** 2)) + 1e-12))
    return np.array(out, np.float32)

def procedural_table(rng, frames=8, formants=(2, 4), tilt=(.6, 1.6)):
    """a wavetable nobody has: a few spectral peaks («formants») that glide across the frames over a 1/h^tilt spectrum, random
    odd/even balance. Different every draw; morph through it with the `pos` destination."""
    h = np.arange(1, TABLE // 4); n = int(rng.integers(formants[0], formants[1] + 1)); til = float(rng.uniform(*tilt)); odd = float(rng.uniform(.2, 1.0))
    c0 = rng.uniform(1.0, 6.5, n); c1 = c0 + rng.uniform(-1.5, 1.5, n); wd = rng.uniform(.25, .8, n); g = rng.uniform(.5, 1.0, n)
    phs = rng.uniform(0, 2 * np.pi, len(h)); out = []
    for f in np.linspace(0, 1, frames):
        env = sum(g[i] * np.exp(-.5 * ((np.log2(h) - (c0[i] + (c1[i] - c0[i]) * f)) / wd[i]) ** 2) for i in range(n))
        amp = (env + .05) / h ** til * np.where(h % 2 == 0, odd, 1.0)
        spec = np.zeros(TABLE // 2 + 1, complex); spec[1:len(h) + 1] = amp * np.exp(1j * phs); cyc = np.fft.irfft(spec, TABLE)
        out.append(cyc / (np.sqrt(np.mean(cyc ** 2)) + 1e-12))
    return np.array(out, np.float32)

# ---- envelopes and filters --------------------------------------------------------------------------------------------
def adsr(tl, dur, a, d, s, r):
    """tl (L, 1) seconds, dur (N,) -> (L, N): linear attack, exponential decay to s, exponential release from wherever it is"""
    a = max(a, 5e-4); d = max(d, 1e-3); r = max(r, 2e-3)
    pre = lambda t: np.where(t < a, t / a, s + (1 - s) * np.exp(-5.0 * (t - a) / d))
    held = pre(tl); off = pre(np.asarray(dur, np.float32)[None, :])
    return np.where(tl < dur[None, :], held, off * np.exp(-5.0 * np.maximum(tl - dur[None, :], 0.0) / r)).astype(np.float32)

_KERNEL = None
def _kernel():
    """the filter loop compiled by numba when numba is installed (it comes with librosa): 50-100x faster, same numbers.
    AUTODJ_NO_NUMBA=1 forces the numpy loop."""
    global _KERNEL
    if _KERNEL is None:
        _KERNEL = False
        if not os.environ.get("AUTODJ_NO_NUMBA"):
            try:
                from numba import njit
                @njit(cache=False)
                def k(X, A1, A2, G, K, mode, hop):
                    L, C, N = X.shape
                    for c in range(C):
                        for j in range(N):
                            ic1 = 0.0; ic2 = 0.0
                            for n in range(L):
                                b = n // hop; x = X[n, c, j]
                                v1 = A1[b, j] * ic1 + A2[b, j] * (x - ic2); v2 = ic2 + G[b, j] * v1
                                ic1 = 2.0 * v1 - ic1; ic2 = 2.0 * v2 - ic2
                                X[n, c, j] = v2 if mode == 0 else v1 if mode == 1 else x - K[b, j] * v1 - v2
                k(np.zeros((2, 1, 1), np.float32), np.ones((1, 1), np.float32), np.ones((1, 1), np.float32), np.ones((1, 1), np.float32), np.ones((1, 1), np.float32), 0, 1)
                _KERNEL = k
            except Exception:
                _KERNEL = False
    return _KERNEL or None

def svf(X, fc, res, sr, mode="lp", poles=4, hop=CTL):
    """zero-delay state-variable filter, time-varying. X (L, C, N); fc (ceil(L/hop), N) Hz and res (same shape or scalar) at
    control rate. 4 poles = a second, non-resonant stage at the same cutoff. Filters X in place and returns it."""
    L = X.shape[0]; G = np.tan(np.pi * np.clip(fc, 16.0, sr * .45) / sr).astype(np.float32); kern = _kernel(); mi = {"lp": 0, "bp": 1}.get(mode, 2)
    for stage in range(2 if poles >= 4 else 1):
        K = ((2.0 - 2.0 * np.clip(res, 0, .97)) * np.ones_like(G)).astype(np.float32) if stage == 0 else np.full_like(G, 1.4142)
        A1 = (1.0 / (1.0 + G * (G + K))).astype(np.float32); A2 = (G * A1).astype(np.float32)
        if kern is not None: kern(X, A1, A2, G, K, mi, hop); continue
        ic1 = np.zeros(X.shape[1:], np.float32); ic2 = np.zeros(X.shape[1:], np.float32)
        for c in range(G.shape[0]):
            a1, a2, g, k = A1[c], A2[c], G[c], K[c]
            for n in range(c * hop, min(L, (c + 1) * hop)):
                x = X[n]; v1 = a1 * ic1 + a2 * (x - ic2); v2 = ic2 + g * v1
                ic1 = 2.0 * v1 - ic1; ic2 = 2.0 * v2 - ic2
                X[n] = v2 if mi == 0 else v1 if mi == 1 else x - k * v1 - v2
    return X

def biquad_stream(x, fc, res, sr, mode="lp", poles=4, hop=CTL):
    """one time-varying resonant filter over a whole (n, C) stream: RBJ biquads whose coefficients change every `hop` samples,
    the state carried across the blocks. For the shared («layer») filter of long notes: ~1 s per minute of audio."""
    n = len(x); nb = -(-n // hop); fc = np.resize(np.clip(fc, 16.0, sr * .45), nb); res = np.resize(res, nb); y = np.array(x, np.float64)
    w = 2 * np.pi * fc / sr; cw, sw = np.cos(w), np.sin(w)
    for stage in range(2 if poles >= 4 else 1):
        Q = .5 / (1.0 - np.clip(res, 0, .97)) if stage == 0 else np.full(nb, .7071); al = sw / (2 * Q); a0 = 1 + al
        if mode == "lp": b = np.stack([(1 - cw) / 2, 1 - cw, (1 - cw) / 2], 1)
        elif mode == "hp": b = np.stack([(1 + cw) / 2, -(1 + cw), (1 + cw) / 2], 1)
        else: b = np.stack([al, np.zeros(nb), -al], 1)
        b = b / a0[:, None]; a = np.stack([np.ones(nb), -2 * cw / a0, (1 - al) / a0], 1); zi = np.zeros((2, y.shape[1]))
        if _stream_kernel() is not None: _stream_kernel()(y, b, a, hop); continue
        for k in range(nb):
            s = slice(k * hop, min(n, (k + 1) * hop)); y[s], zi = lfilter(b[k], a[k], y[s], axis=0, zi=zi)
    return y.astype(np.float32)

_SKERNEL = None
def _stream_kernel():
    """numba version of the block loop above (transposed direct form II, the state carried on); None without numba"""
    global _SKERNEL
    if _SKERNEL is None:
        _SKERNEL = False
        if not os.environ.get("AUTODJ_NO_NUMBA"):
            try:
                from numba import njit
                @njit(cache=False)
                def k(y, b, a, hop):
                    n, C = y.shape
                    for c in range(C):
                        z1 = 0.0; z2 = 0.0
                        for i in range(n):
                            q = i // hop; x = y[i, c]; o = b[q, 0] * x + z1
                            z1 = b[q, 1] * x - a[q, 1] * o + z2; z2 = b[q, 2] * x - a[q, 2] * o; y[i, c] = o
                k(np.zeros((2, 1)), np.ones((1, 3)), np.ones((1, 3)), 1)
                _SKERNEL = k
            except Exception:
                _SKERNEL = False
    return _SKERNEL or None

# ---- the synth --------------------------------------------------------------------------------------------------------
class Synth:
    def __init__(self, p=None, bpm=120.0, sr=SR, seed=0, tables=None):
        self.p = patch(p); self.bpm, self.sr, self.seed = float(bpm), sr, seed
        self.tables = {k: mipmap(v) for k, v in (tables or {}).items()}
        for o in self.p["osc"]:
            if o["wave"] == "wt" and o.get("table") not in self.tables: raise ValueError(f"osc wave 'wt' needs tables[{o.get('table')!r}]")
        f = self.p["filt"]; hot = f["drive"] > 0 or any(o["wave"] == "fm" and (o["index"] > 0 or any(m["dst"] == "index" for m in self.p["mods"])) for o in self.p["osc"])
        self.os = int(self.p["os"]) or (2 if hot else 1)

    def render(self, events, total_s, ctl=None):
        """events (t, midi, vel 1-127, dur_s) -> (n, 2) float32. ctl: {name: curve of the track's length} for "ctl:name" sources."""
        n = int(total_s * self.sr); out = np.zeros((n + self.sr * 4, 2), np.float32); ev = sorted(events, key=lambda e: e[0])
        if not ev: return out[:n]
        p = self.p; t0 = np.array([e[0] for e in ev], np.float64); m = np.array([e[1] for e in ev], np.float32)
        v = np.clip(np.array([e[2] for e in ev], np.float32) / 127.0, 0, 1); d = np.maximum(np.array([e[3] for e in ev], np.float32), .005)
        prev = m.copy()                                                              # glide: only from a note that is still sounding
        if p["glide_ms"] > 0: leg = t0[1:] - (t0[:-1] + d[:-1]) < .03; prev[1:] = np.where(leg, m[:-1], m[1:])
        per = p["filt"]["per"]; per = ("layer" if np.median(d) > 1.5 else "note") if per == "auto" else per
        rng = np.random.default_rng(self.seed); nr = sum(1 for q in p["mods"] if q["src"] == "rand"); U = max(o["unison"] for o in p["osc"])
        note_rand = rng.uniform(-1, 1, (len(ev), max(1, nr))).astype(np.float32); note_ph = rng.uniform(0, 1, (len(ev), len(p["osc"]), U))
        dry = np.zeros_like(out) if per == "layer" else None; fenv_ctl = np.zeros(-(-len(out) // CTL), np.float32) if per == "layer" else None
        order = np.argsort(d, kind="stable"); i = 0; tail = p["amp"]["r"] * 1.3 + .01
        while i < len(order):                                                        # batches of similar length
            j = i + 1
            while j < len(order) and int((d[order[j]] + tail) * self.sr * self.os) * (j - i + 1) <= CAP: j += 1
            ix = order[i:j]; i = j
            Y, fe = self._batch(ix, t0[ix], m[ix], v[ix], d[ix], prev[ix], note_rand[ix], note_ph[ix], per, ctl or {}, total_s)
            for q, k in enumerate(ix):
                a = int(round(t0[k] * self.sr))
                if a < 0 or a >= len(out): continue
                ln = min(Y.shape[0], len(out) - a); (dry if per == "layer" else out)[a:a + ln] += Y[:ln, :, q]
                if fe is not None:
                    c0 = a // CTL; c1 = min(len(fenv_ctl), c0 + len(fe)); fenv_ctl[c0:c1] = np.maximum(fenv_ctl[c0:c1], fe[:c1 - c0, q])
        if per == "layer": out = self._layer_filter(dry, fenv_ctl, ctl or {}, total_s)
        return post(out[:n], p["fx"], self.sr, bpm=self.bpm)

    # mod sources -> destination sums --------------------------------------------------------------------------------------
    def _src(self, q, k, tl, t0, v, fenv, aenv, note_rand, ctl, total_s, sr, stream=False):
        s = q["src"]; ta = lambda: t0[None, :] + tl.astype(np.float64)
        if s == "time" and stream: return np.clip(tl / max(total_s, 1e-9), 0, 1).astype(np.float32)
        if s == "vel": return v[None, :]
        if s == "rand": return note_rand[None, :, k]
        if s == "env": return fenv
        if s == "amp_env": return aenv
        if s == "pos": return ((t0 / (240.0 / self.bpm)) % 1.0).astype(np.float32)[None, :]
        if s == "time": return np.clip(t0 / max(total_s, 1e-9), 0, 1).astype(np.float32)[None, :]
        if s in ("lfo", "lfo_note"):
            ph = (ta() if s == "lfo" else tl.astype(np.float64)) * rate_hz(q.get("rate", "1b"), self.bpm) + q.get("phase", 0.0)
            sh = q.get("shape", "sine")
            if sh == "tri": return (4 * np.abs(ph % 1.0 - .5) - 1).astype(np.float32)
            if sh == "saw": return (2 * (ph % 1.0) - 1).astype(np.float32)
            if sh == "sh": return (np.sin(np.floor(ph) * 12.9898 + self.seed) * 43758.5453 % 2.0 - 1.0).astype(np.float32)
            return np.sin(2 * np.pi * ph).astype(np.float32)
        if s.startswith("ctl:"):
            c = ctl.get(s[4:])
            if c is None: raise KeyError(f"mod source {s!r}: pass ctl={{{s[4:]!r}: curve}} to render()")
            c = np.asarray(c, np.float32).reshape(-1); return c[np.clip((ta() * self.sr).astype(np.int64), 0, len(c) - 1)]
        raise ValueError(f"unknown mod source {s!r}")

    def _mods(self, tl, t0, v, fenv, aenv, note_rand, ctl, total_s, sr, skip_dst=(), stream=False):
        """destination -> summed modulation. stream=True: the shared layer filter (only cutoff / res, only sources that exist
        without a note: lfo, time, ctl); skip_dst: destinations handled elsewhere."""
        acc = {}; k = -1
        for q in self.p["mods"]:
            k += q["src"] == "rand"
            if q["dst"] in skip_dst: continue
            if stream and (q["dst"] not in ("cutoff", "res") or not (q["src"] in ("lfo", "time") or q["src"].startswith("ctl:"))): continue
            acc[q["dst"]] = acc.get(q["dst"], 0.0) + self._src(q, max(k, 0), tl, t0, v, fenv, aenv, note_rand, ctl, total_s, sr, stream) * float(q.get("amt", 1.0))
        return acc

    def _batch(self, ix, t0, m, v, d, prev, note_rand, note_ph, per, ctl, total_s):
        p = self.p; sr = self.sr * self.os; N = len(ix); L = int((d.max() + p["amp"]["r"] * 1.3 + .01) * sr)
        tl = (np.arange(L, dtype=np.float32) / sr)[:, None]; F = p["fenv"]; A = p["amp"]
        fenv = adsr(tl, d, F["a"], F["d"], F["s"], F["r"]); aenv = adsr(tl, d, A["a"], A["d"], A["s"], A["r"])
        md = self._mods(tl, t0, v, fenv, aenv, note_rand, ctl, total_s, sr, ("cutoff", "res") if per == "layer" else ())   # layer: the shared filter has them
        pm = md.get("pitch", 0.0)
        if p["glide_ms"] > 0: pm = pm + (prev - m)[None, :] * np.exp(-tl / (p["glide_ms"] / 3000.0))
        Lc = np.zeros((L, N), np.float32); Rc = None; rng = np.random.default_rng([self.seed, int(ix[0]), N])
        for oi, o in enumerate(p["osc"]):
            U = int(o["unison"]); f0 = 440.0 * 2 ** ((m + o["semi"] - 69.0) / 12.0 + o["cents"] / 1200.0)
            for u in range(U):
                off = (u / (U - 1) * 2 - 1) if U > 1 else 0.0; det = o["detune"] * off * (1.0 + md.get("detune", 0.0)) / 100.0
                st = pm + det
                if p["drift"] > 0: st = st + (p["drift"] / 100.0) * np.sin(2 * np.pi * rng.uniform(.15, .6, N)[None, :] * (t0[None, :] + tl) + rng.uniform(0, 6.28, N)[None, :])
                ph0 = (note_ph[:, oi, u] if (o["phase"] is None and U > 1) else np.full(N, float(o["phase"] or 0.0)))[None, :]
                if np.ndim(st) < 2 or np.shape(st)[0] == 1:                               # constant pitch inside the note: no cumsum
                    fq = f0[None, :] * 2 ** (np.asarray(st, np.float64).reshape(1, -1) / 12.0); ph = fq * tl.astype(np.float64) + ph0; dt = (fq / sr) * np.ones((1, N))
                else:
                    fq = f0[None, :] * 2 ** (st.astype(np.float64) / 12.0); ph = np.cumsum(fq / sr, axis=0) + ph0; dt = fq / sr
                w = o["wave"]
                if w == "saw": y = _saw(ph, dt)
                elif w == "pulse": y = .5 * (_saw(ph, dt) - _saw(ph + np.clip(o["pw"] + md.get("pw", 0.0), .05, .95), dt))
                elif w == "tri": y = 4.0 * np.abs(ph % 1.0 - .5) - 1.0
                elif w == "sine": y = np.sin(2 * np.pi * ph)
                elif w == "noise": y = rng.standard_normal((L, N))
                elif w == "fm": y = np.sin(2 * np.pi * ph + np.maximum(0.0, o["index"] + md.get("index", 0.0)) * np.sin(2 * np.pi * ph * o["ratio"]))
                elif w == "wt": y = _wt(self.tables[o["table"]], ph, np.clip(o["pos"] + md.get("pos", 0.0), 0, 1) * np.ones((1, N)), np.max(fq, axis=0) * np.ones(N), sr)
                else: raise ValueError(f"unknown wave {w!r}")
                y = (y * (o["level"] / np.sqrt(U))).astype(np.float32); pan = o["spread"] * off * (1 if u % 2 == 0 else -1)
                if pan == 0 and Rc is None: Lc += y
                else:
                    if Rc is None: Rc = Lc.copy()
                    th = (pan + 1) * np.pi / 4; Lc += y * (np.cos(th) * 1.4142); Rc += y * (np.sin(th) * 1.4142)
        X = np.stack([Lc, Rc if Rc is not None else Lc], 1) if Rc is not None else Lc[:, None, :]      # (L, C, N)
        f = p["filt"]
        if f["drive"] > 0: g = 10 ** (f["drive"] / 20); X = (np.tanh(X * g) / np.tanh(g)).astype(np.float32)
        fe_out = None
        if per == "note":
            c = slice(None, None, CTL)
            octs = f["env"] * fenv[c] + f["key"] * ((m - 60.0) / 12.0)[None, :] + f["vel"] * v[None, :] + (md.get("cutoff", 0.0) * np.ones((L, N), np.float32))[c]
            res = f["res"] + (md.get("res", 0.0) * np.ones((L, N), np.float32))[c] if "res" in md else f["res"]
            X = svf(np.ascontiguousarray(X), f["cutoff"] * 2 ** octs, res, sr, f["mode"], f["poles"])
        else: fe_out = (fenv * v[None, :] ** .5)[::CTL * self.os]                       # the shared filter's envelope: loudest note wins
        vg = (1 - A["vel"]) + A["vel"] * v * v; gain = aenv * vg[None, :]
        if "amp" in md: gain = gain * 10 ** (md["amp"] / 20.0)
        X = X * gain[:, None, :]
        pn = np.clip(md.get("pan", 0.0) * np.ones((1, N), np.float32), -1, 1)
        if X.shape[1] == 1: X = np.repeat(X, 2, 1)
        if np.any(pn != 0):
            th = (pn + 1) * np.pi / 4; X = X * np.stack([np.cos(th) * 1.4142, np.sin(th) * 1.4142], 1).astype(np.float32)
        k = min(L, int(.002 * sr)); X[-k:] *= np.linspace(1, 0, k, dtype=np.float32)[:, None, None]
        if self.os > 1: X = resample_poly(X, 1, self.os, axis=0).astype(np.float32)
        return X.astype(np.float32), fe_out

    def _layer_filter(self, dry, fenv_ctl, ctl, total_s):
        """per="layer": the summed voices pass ONE filter; its cutoff follows the note envelopes (loudest wins) and the global mods"""
        f = self.p["filt"]; nb = len(fenv_ctl); tl = (np.arange(nb, dtype=np.float32) * CTL / self.sr)[:, None]; z = np.zeros(1, np.float32)
        md = self._mods(tl, np.zeros(1), z, fenv_ctl[:, None], fenv_ctl[:, None], np.zeros((1, 1), np.float32), ctl, total_s, self.sr, stream=True)
        octs = f["env"] * fenv_ctl + np.reshape(md.get("cutoff", 0.0) * np.ones((nb, 1), np.float32), -1)
        res = f["res"] + np.reshape(md.get("res", 0.0) * np.ones((nb, 1), np.float32), -1)
        return biquad_stream(dry, f["cutoff"] * 2 ** octs, res, self.sr, f["mode"], f["poles"])

# ---- post effects of a patch ------------------------------------------------------------------------------------------
def comb(x, sr, midi, fb=.6, mix=.5, damp=.5):
    """a resonator tuned to a note: a feedback comb whose pitch is `midi`. Anything percussive sent through it rings on that note
    (drums that sing the key of the track, a noise burst that becomes a plucked string)."""
    D = max(2, int(round(sr / (440.0 * 2 ** ((midi - 69) / 12.0))))); y = np.array(x, np.float32); fb = float(np.clip(fb, 0, .98))
    for k in range(D, len(y), D):
        prv = y[k - D:k][:len(y) - k]; sm = prv.copy(); sm[1:] = (1 - damp) * prv[1:] + damp * prv[:-1]       # darker every round
        y[k:k + D] += fb * sm
    return ((1 - mix) * x + mix * y * (1 - fb)).astype(np.float32)

def post(x, fx, sr=SR, bpm=120.0):
    """the patch's own effects, in this order: drive (dB) -> crush (bits) -> comb {midi, fb, mix} -> chorus (0..1) -> phaser (0..1)
    -> hpf / lpf (Hz) -> width (side gain above 400 Hz)"""
    if not fx: return x
    from .core import sat, pb
    if fx.get("drive"): x = sat(x, fx["drive"])
    if fx.get("crush"): q = 2 ** (float(fx["crush"]) - 1); x = (np.round(x / (np.abs(x).max() + 1e-9) * q) / q * (np.abs(x).max() + 1e-9)).astype(np.float32)
    if fx.get("comb"): x = comb(x, sr, **fx["comb"])
    chain = []
    if fx.get("chorus") or fx.get("phaser") or fx.get("hpf") or fx.get("lpf"):
        from pedalboard import Pedalboard, Chorus, Phaser, HighpassFilter, LowpassFilter
        if fx.get("chorus"): chain.append(Chorus(rate_hz=.35, depth=.25 * float(fx["chorus"]) + .05, centre_delay_ms=9.0, feedback=.1, mix=.5 * float(fx["chorus"])))
        if fx.get("phaser"): chain.append(Phaser(rate_hz=rate_hz("4b", bpm), depth=.6, centre_frequency_hz=900.0, feedback=.3, mix=.5 * float(fx["phaser"])))
        if fx.get("hpf"): chain.append(HighpassFilter(float(fx["hpf"])))
        if fx.get("lpf"): chain.append(LowpassFilter(float(fx["lpf"])))
        x = pb(Pedalboard(chain), x, sr)
    if fx.get("width"):
        from .stereo import ms_widen
        x = ms_widen(x, float(fx["width"]), sr=sr)
    return x.astype(np.float32)
